-- Guarded delete for the event log (SPOOL-194; decision recorded on the ticket, ADR-0006 amendment queued).
-- The event table stays append-only in the database: UPDATE is always refused (trigger from 0001,
-- unchanged) and DELETE is refused unless the same transaction holds an open grant for that event's
-- tenant. Only tenant deletion (and later the aggregation job) and demo removal open a grant.
--
-- How a grant works, in one atomic batch:
--   1. INSERT a row into event_delete_grant for one tenant (scope 'tenant'), or for one tenant's
--      filament (scope 'filament': only events about that filament or its clips).
--   2. DELETE the events. The trigger below lets a row go only if a matching grant exists.
--   3. DELETE the grant row.
-- A grant cannot outlive its batch. Its must_close column is a deferred foreign key to a location id
-- that can never exist (location ids are 1 to 64 characters; must_close is always ''), so a grant row
-- still present at COMMIT fails the commit and the whole batch rolls back, deletes included. A batch
-- that fails midway rolls back too, so a grant is never visible outside the transaction that opened it.
-- This relies on foreign keys being enforced, which they are on every connection (openDatabase) and
-- on D1 by default. If they were off, the event foreign keys would be unenforced as well.
-- Do not edit this file after it has been applied anywhere: add a new numbered migration.

CREATE TABLE event_delete_grant (
  tenant_id TEXT NOT NULL CHECK (
    length(tenant_id) BETWEEN 1 AND 64 AND tenant_id NOT GLOB '*[^A-Za-z0-9._:-]*'
  ),
  scope TEXT NOT NULL CHECK (scope IN ('tenant', 'filament')),
  filament_id TEXT,
  must_close TEXT NOT NULL DEFAULT '' CHECK (must_close = ''),
  PRIMARY KEY (tenant_id, scope),
  CHECK ((scope = 'tenant') = (filament_id IS NULL)),
  FOREIGN KEY (tenant_id, filament_id) REFERENCES filament (tenant_id, id),
  FOREIGN KEY (tenant_id, must_close) REFERENCES location (tenant_id, id)
    DEFERRABLE INITIALLY DEFERRED,
  CHECK (instr(CAST(tenant_id AS BLOB), x'00') = 0)
) STRICT;

-- A grant is opened and closed, never changed: changing its tenant or filament would widen it.
CREATE TRIGGER event_delete_grant_is_not_updated
BEFORE UPDATE ON event_delete_grant
BEGIN
  SELECT RAISE(ABORT, 'event delete grants cannot be changed');
END;

-- Same name and message as in 0001; the only change is the grant check.
DROP TRIGGER event_is_append_only_delete;

CREATE TRIGGER event_is_append_only_delete
BEFORE DELETE ON event
BEGIN
  SELECT RAISE(ABORT, 'event is append-only')
  WHERE NOT EXISTS (
    SELECT 1 FROM event_delete_grant g
     WHERE g.tenant_id = OLD.tenant_id
       AND (
         g.scope = 'tenant'
         OR (
           g.scope = 'filament'
           AND (
             OLD.filament_id = g.filament_id
             OR EXISTS (
               SELECT 1 FROM clip k
                WHERE k.tenant_id = OLD.tenant_id AND k.id = OLD.clip_id
                  AND k.filament_id = g.filament_id
             )
           )
         )
       )
  );
END;
