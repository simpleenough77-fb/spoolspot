-- Boxed stock belongs at passive storage only (SPOOL-200, owner decision 2026-11-12). Active storage and
-- active use hold opened spools through their clips; clip storage holds clips. A stock line is therefore
-- refused at any leaf whose type is not passive_storage, and a passive leaf that holds stock lines cannot
-- be changed to another leaf type. Containers are already refused by the triggers in 0001.
--
-- Additive only: existing rows are not changed. A database that already has stock lines at other leaf
-- types keeps them where they are (they are not deleted or moved). Their counts can still go down
-- through the API, because a count change does not change the location; they can never go up. To list them:
--   SPOOLSPOT_DB=<path to the database> node scripts/stock-off-passive.ts
-- (the script reads SPOOLSPOT_DB, default data/spoolspot.db, and opens the database read only).
-- Do not edit this file after it has been applied anywhere: add a new numbered migration.

CREATE TRIGGER stock_line_location_is_passive_insert
BEFORE INSERT ON stock_line
BEGIN
  SELECT RAISE(ABORT, 'boxed stock belongs at passive storage')
  WHERE EXISTS (
    SELECT 1 FROM location l
    WHERE l.tenant_id = NEW.tenant_id AND l.id = NEW.location_id
      AND l.leaf = 1 AND l.type <> 'passive_storage'
  );
END;

-- Also on filament_id and pack: a line left off passive storage by an older database cannot become a
-- different line (another filament or pack) where it is; it can only be counted down.
CREATE TRIGGER stock_line_location_is_passive_update
BEFORE UPDATE OF location_id, tenant_id, filament_id, pack ON stock_line
BEGIN
  SELECT RAISE(ABORT, 'boxed stock belongs at passive storage')
  WHERE EXISTS (
    SELECT 1 FROM location l
    WHERE l.tenant_id = NEW.tenant_id AND l.id = NEW.location_id
      AND l.leaf = 1 AND l.type <> 'passive_storage'
  );
END;

-- A line left at another leaf type by an older database can only go down (so it can be cleared), never up.
CREATE TRIGGER stock_line_off_passive_only_goes_down
BEFORE UPDATE OF count ON stock_line
WHEN NEW.count > OLD.count
BEGIN
  SELECT RAISE(ABORT, 'boxed stock belongs at passive storage')
  WHERE EXISTS (
    SELECT 1 FROM location l
    WHERE l.tenant_id = NEW.tenant_id AND l.id = NEW.location_id
      AND l.leaf = 1 AND l.type <> 'passive_storage'
  );
END;

-- A passive leaf that holds stock lines stays passive. Changing it to a container is covered by 0001
-- ("must stay a leaf"), so only the other leaf types are checked here.
CREATE TRIGGER location_with_stock_stays_passive
BEFORE UPDATE OF type ON location
WHEN NEW.type <> 'passive_storage' AND NEW.type <> 'container' AND OLD.type IS NOT NEW.type
BEGIN
  SELECT RAISE(ABORT, 'boxed stock belongs at passive storage')
  WHERE EXISTS (
    SELECT 1 FROM stock_line s WHERE s.tenant_id = OLD.tenant_id AND s.location_id = OLD.id
  );
END;
